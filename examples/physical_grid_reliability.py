"""Frozen physical-grid reliability experiment; no real observed depths are fitted.

Run as ``python -m examples.physical_grid_reliability --grid ... --output ...``.
Input grids are generated by examples.prepare_physical_grid. Main runs require
clean committed source and the exact committed configuration.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import subprocess
import time
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

import numpy as np

from tierra_plus.diagnostics.network import fit
from tierra_plus.diagnostics.physical_grid import (
    FiniteSpectralGrid,
    calibration_radius,
    remove_offset,
)

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "examples/configs/physical-grid-v1.json"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_grid(path: Path) -> tuple[dict, dict]:
    manifest = json.loads((path / "manifest.json").read_text())
    if digest(path / "grid.npz") != manifest["grid_sha256"]:
        raise ValueError("Prepared grid checksum mismatch")
    with np.load(path / "grid.npz", allow_pickle=False) as saved:
        arrays = {key: saved[key] for key in saved.files}
    arrays["labels"] = np.array([x["log_metallicity"] for x in manifest["states"]])
    if arrays["spectra"].shape != (len(manifest["states"]), 4, len(arrays["sigma"])):
        raise ValueError("Prepared grid shape mismatch")
    if manifest["family"] == "rcte":
        expected = {
            "train": [i for i, x in enumerate(manifest["states"]) if x["tint"] in (100, 300)],
            "validation": [
                i
                for i, x in enumerate(manifest["states"])
                if x["tint"] == 200 and x["heat_redistribution"] == 0.4
            ],
            "test": [
                i
                for i, x in enumerate(manifest["states"])
                if x["tint"] == 200 and x["heat_redistribution"] == 0.5
            ],
        }
        if manifest["splits"] != expected or [len(x) for x in expected.values()] != [128, 32, 32]:
            raise ValueError("Physical split violates the frozen protocol")
        if sorted(sum(expected.values(), [])) != list(range(len(manifest["states"]))):
            raise ValueError("Physical split is incomplete or overlapping")
    return manifest, arrays


def nuisance_grid(spectra: np.ndarray, config: dict) -> np.ndarray:
    return np.stack(
        [
            spectra[:, shift] / (1 + dilution)
            for shift in range(3)
            for dilution in config["nuisance_dilutions"]
        ],
        axis=1,
    )


def split_draws(
    config: dict, seed: int, split: int, states: list[int], repeats: int, bins: int
) -> dict:
    words = [config["data_seed"], seed, split]
    rng = np.random.default_rng(np.random.SeedSequence(words))
    ids = np.repeat(states, repeats)
    return {
        "state": ids,
        "noise": rng.standard_normal((len(ids), bins)),
        "rng": rng,
        "seed_words": words,
    }


def ridge_fit(x: np.ndarray, y: np.ndarray, penalty: float) -> dict:
    mean, scale = x.mean(axis=0), x.std(axis=0)
    scale[scale < 1e-12] = 1
    centered = (x - mean) / scale
    coefficient = np.linalg.solve(
        centered.T @ centered + penalty * np.eye(x.shape[1]), centered.T @ (y - y.mean())
    )
    return {
        "mean": mean,
        "scale": scale,
        "coefficient": coefficient,
        "intercept": np.array([y.mean()]),
    }


def ridge_predict(model: dict, x: np.ndarray) -> np.ndarray:
    return ((x - model["mean"]) / model["scale"]) @ model["coefficient"] + model["intercept"][0]


def interval(mean: np.ndarray, radius: float) -> dict:
    return {"mean": mean, "lower": mean - radius, "upper": mean + radius}


def metrics(truth: np.ndarray, ids: np.ndarray, result: dict, width_cap: float) -> dict:
    error = result["mean"] - truth
    width = result["upper"] - result["lower"]
    covered = (truth >= result["lower"]) & (truth <= result["upper"])
    accepted = width <= width_cap
    if "accept" in result:
        accepted &= result["accept"]
    if not np.isfinite(np.concatenate([error, width])).all() or np.any(width < 0):
        raise ValueError("Nonfinite or reversed prediction interval")
    by_state = []
    for state in np.unique(ids):
        mask = ids == state
        chosen = mask & accepted
        by_state.append(
            {
                "state": int(state),
                "rmse": float(np.sqrt(np.mean(error[mask] ** 2))),
                "coverage90": float(covered[mask].mean()),
                "acceptance": float(accepted[mask].mean()),
                "accepted_coverage90": float(covered[chosen].mean()) if chosen.any() else None,
            }
        )
    return {
        "n": len(truth),
        "physical_states": len(by_state),
        "rmse_dex": float(np.sqrt(np.mean(error**2))),
        "bias_dex": float(error.mean()),
        "coverage90": float(covered.mean()),
        "mean_width_dex": float(width.mean()),
        "median_width_dex": float(np.median(width)),
        "acceptance": float(accepted.mean()),
        "accepted_count": int(accepted.sum()),
        "accepted_coverage90": float(covered[accepted].mean()) if accepted.any() else None,
        "accepted_rmse_dex": (
            float(np.sqrt(np.mean(error[accepted] ** 2))) if accepted.any() else None
        ),
        "by_state": by_state,
    }


def reliable(row: dict, config: dict) -> bool:
    return bool(
        row["coverage90"] >= config["coverage_floor"]
        and row["acceptance"] >= config["acceptance_floor"]
        and row["accepted_coverage90"] is not None
        and row["accepted_coverage90"] >= config["coverage_floor"]
    )


def decisions(runs: list[dict], required: int, smoke: bool) -> dict:
    counts = {
        method: sum(x["gates"]["classical_reliability"][method] for x in runs)
        for method in runs[0]["gates"]["classical_reliability"]
    }
    neural_count = sum(x["gates"]["augmented_network"] for x in runs)
    return {
        "required_seed_passes": required,
        "augmented_network_seed_passes": neural_count,
        "augmented_network_pass": not smoke and neural_count >= required,
        "classical_seed_passes": counts,
        "classical_pass": {key: not smoke and value >= required for key, value in counts.items()},
    }


def run_seed(
    config: dict, seed: int, manifest: dict, arrays: dict, external: tuple | None, output: Path
) -> dict:
    spectra, sigma, labels = arrays["spectra"], arrays["sigma"], arrays["labels"]
    train_ids = manifest["splits"]["train"]
    training = split_draws(
        config, seed, 0, train_ids, config["training_repeats_per_state"], len(sigma)
    )
    state = training["state"]
    candidates = nuisance_grid(spectra, config)
    nominal = spectra[state, 1] + training["noise"] * sigma
    chosen_nuisance = training["rng"].integers(candidates.shape[1], size=len(state))
    augmented = candidates[state, chosen_nuisance] + training["noise"] * sigma
    model_inputs = {
        "nominal": remove_offset(nominal, sigma),
        "augmented": remove_offset(augmented, sigma),
    }
    networks, ridges, weights = {}, {}, {}
    for kind, x in model_inputs.items():
        networks[kind] = fit(
            x,
            labels[state],
            seed,
            hidden=config["hidden_width"],
            steps=config["training_steps"],
            batch_size=config["batch_size"],
            learning_rate=config["learning_rate"],
        )
        ridges[kind] = ridge_fit(x, labels[state], config["ridge_penalty"])
        for key, value in networks[kind].state_dict().items():
            weights[f"network_{kind}_{key}"] = value
        for key, value in ridges[kind].items():
            weights[f"ridge_{kind}_{key}"] = value

    def predictions(y: np.ndarray) -> dict:
        x = remove_offset(y, sigma)
        return {
            "network": networks["nominal"].predict(x),
            "augmented_network": networks["augmented"].predict(x),
            "ridge": ridge_predict(ridges["nominal"], x),
            "augmented_ridge": ridge_predict(ridges["augmented"], x),
        }

    reference = FiniteSpectralGrid(candidates, labels, sigma)
    nominal_reference = FiniteSpectralGrid(spectra[:, 1:2], labels, sigma)
    training_reference = FiniteSpectralGrid(candidates[train_ids], labels[train_ids], sigma)
    validation = split_draws(
        config,
        seed,
        1,
        manifest["splits"]["validation"],
        config["validation_repeats_per_state"],
        len(sigma),
    )
    val_state, val_noise = validation["state"], validation["noise"]
    radii, clean_radii = {}, {}
    for nuisance in range(candidates.shape[1]):
        y = candidates[val_state, nuisance] + val_noise * sigma
        for method, prediction in predictions(y).items():
            radius = calibration_radius(labels[val_state] - prediction)
            radii[method] = max(radii.get(method, 0), radius)
            if nuisance == 3:  # shift=0, dilution=0 in the fixed 3x3 enumeration
                clean_radii[method] = radius
    val_clean = spectra[val_state, 1] + val_noise * sigma
    residual_threshold = float(
        np.quantile(nominal_reference.infer(val_clean)["chi2"], 0.95, method="higher")
    )
    samples = {
        "training_state": state,
        "training_noise": training["noise"],
        "training_nuisance": chosen_nuisance,
        "validation_state": val_state,
        "validation_noise": val_noise,
    }
    rows, prediction_arrays = [], {}
    tests = [("test", manifest, arrays, manifest["splits"]["test"], 2)]
    if external is not None:
        ext_manifest, ext_arrays = external
        if not np.array_equal(sigma, ext_arrays["sigma"]):
            raise ValueError("External measurement geometry differs")
        tests.append(
            ("photochemical", ext_manifest, ext_arrays, ext_manifest["splits"]["external"], 3)
        )
    for family, _, data, ids, split in tests:
        draws = split_draws(config, seed, split, ids, config["test_repeats_per_state"], len(sigma))
        state, noise = draws["state"], draws["noise"]
        truth = data["labels"][state]
        samples[f"{family}_state"], samples[f"{family}_noise"], samples[f"{family}_truth"] = (
            state,
            noise,
            truth,
        )
        baseline = {}
        for condition in config["primary_conditions"] + [config["secondary_condition"]]:
            name = condition["name"]
            y = (
                data["spectra"][state, condition["shift_index"]] / (1 + condition["dilution"])
                + noise * sigma
            )
            learned = predictions(y)
            outputs = {}
            for method, prediction in learned.items():
                radius = radii[method] if method.startswith("augmented") else clean_radii[method]
                outputs[method] = interval(prediction, radius)
                if not method.startswith("augmented"):
                    outputs[method + "_worst_group"] = interval(prediction, radii[method])
            nominal_result, joint, train_result = (
                nominal_reference.infer(y),
                reference.infer(y),
                training_reference.infer(y),
            )
            outputs["grid_nominal"] = nominal_result
            outputs["grid_nominal_checked"] = {
                **nominal_result,
                "accept": nominal_result["chi2"] <= residual_threshold,
            }
            outputs["grid_marginal"] = joint
            outputs["grid_envelope"] = {
                "mean": joint["mean"],
                "lower": joint["envelope_lower"],
                "upper": joint["envelope_upper"],
            }
            outputs["training_grid_marginal"] = train_result
            for method, result in outputs.items():
                if name == "clean":
                    baseline[method] = result["mean"]
                row = metrics(truth, state, result, config["width_cap_dex"])
                row.update(
                    {
                        "family": family,
                        "condition": name,
                        "method": method,
                        "paired_nuisance_rms_dex": float(
                            np.sqrt(np.mean((result["mean"] - baseline[method]) ** 2))
                        ),
                    }
                )
                rows.append(row)
                for key in ("mean", "lower", "upper"):
                    prediction_arrays[f"{family}__{name}__{method}__{key}"] = result[key]
                if "accept" in result:
                    prediction_arrays[f"{family}__{name}__{method}__accept"] = result["accept"]
    primary_names = {x["name"] for x in config["primary_conditions"]}
    primary = [x for x in rows if x["family"] == "test" and x["condition"] in primary_names]
    grouped = {
        method: [x for x in primary if x["method"] == method]
        for method in {x["method"] for x in primary}
    }
    candidate, cheap, ordinary = (
        grouped[k] for k in ("augmented_network", "augmented_ridge", "network")
    )

    def aggregate(records: list[dict], field: str) -> float:
        return float(np.mean([x[field] for x in records]))

    clean_candidate = next(x for x in candidate if x["condition"] == "clean")
    clean_ordinary = next(x for x in ordinary if x["condition"] == "clean")
    components = {
        "coverage_width_acceptance": all(reliable(x, config) for x in candidate),
        "beats_augmented_ridge_rmse": aggregate(candidate, "rmse_dex")
        <= config["neural_rmse_ratio_to_augmented_ridge"] * aggregate(cheap, "rmse_dex"),
        "nuisance_response_reduced": aggregate(candidate, "paired_nuisance_rms_dex")
        <= config["neural_nuisance_response_ratio"]
        * aggregate(ordinary, "paired_nuisance_rms_dex"),
        "clean_quality_retained": clean_candidate["rmse_dex"]
        <= config["neural_clean_rmse_ratio"] * clean_ordinary["rmse_dex"]
        + config["neural_clean_rmse_slack_dex"],
    }
    gates = {
        "augmented_network": all(components.values()),
        "neural_components": components,
        "classical_reliability": {
            method: all(reliable(x, config) for x in grouped[method])
            for method in (
                "grid_marginal",
                "grid_envelope",
                "training_grid_marginal",
                "augmented_ridge",
                "ridge_worst_group",
            )
        },
    }
    seed_output = output / f"seed-{seed}"
    seed_output.mkdir()
    np.savez_compressed(seed_output / "fit.npz", **weights)
    np.savez_compressed(seed_output / "draws.npz", **samples)
    np.savez_compressed(seed_output / "predictions.npz", **prediction_arrays)
    result = {
        "seed": seed,
        "radii_worst_group_dex": radii,
        "radii_clean_dex": clean_radii,
        "residual_threshold": residual_threshold,
        "metrics": rows,
        "gates": gates,
        "artifact_sha256": {p.name: digest(p) for p in sorted(seed_output.glob("*.npz"))},
    }
    (seed_output / "summary.json").write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    return result


def run(grid: Path, output: Path, external_grid: Path | None = None, smoke: bool = False) -> dict:
    config = json.loads(CONFIG.read_text())

    def git(*args: str) -> str:
        return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()

    source = git("rev-parse", "HEAD")
    if not smoke and git("status", "--porcelain"):
        raise ValueError("Main run requires clean committed source")
    if not smoke and any(
        os.environ.get(key) != "1"
        for key in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS")
    ):
        raise ValueError("Set OPENBLAS_NUM_THREADS=OMP_NUM_THREADS=VECLIB_MAXIMUM_THREADS=1")
    if smoke:
        config = {
            **config,
            "seeds": [991],
            "data_seed": config["data_seed"] + 1,
            "training_repeats_per_state": 2,
            "validation_repeats_per_state": 2,
            "test_repeats_per_state": 2,
            "training_steps": 10,
        }
    manifest, arrays = load_grid(grid)
    if manifest["family"] != "rcte":
        raise ValueError("Training requires the RCTE grid")
    if smoke:
        if external_grid is not None:
            raise ValueError("Smoke must never open external heldout spectra")
        # Engineering checks only: deliberately reuse training states, never
        # calibration/test physical states. These outcomes cannot support gates.
        manifest = {
            **manifest,
            "splits": {
                **manifest["splits"],
                "validation": manifest["splits"]["train"][:16],
                "test": manifest["splits"]["train"][16:32],
            },
        }
    external = load_grid(external_grid) if external_grid is not None else None
    if external is not None and external[0]["family"] != "photochemical":
        raise ValueError("External challenge requires the photochemical grid")
    output.mkdir(parents=True, exist_ok=False)
    started, clock = datetime.now(UTC).isoformat(), time.monotonic()
    provenance = {
        "status": "started",
        "smoke": smoke,
        "source_commit": source,
        "config_sha256": digest(CONFIG),
        "config": config,
        "started_utc": started,
        "input_manifest_sha256": {
            "rcte": digest(grid / "manifest.json"),
            "photochemical": digest(external_grid / "manifest.json") if external_grid else None,
        },
        "control_roles": {
            "grid_nominal": "full-grid oracle; includes test states",
            "grid_marginal": "full-grid oracle; includes test states",
            "grid_envelope": "full-grid oracle; includes test states",
            "grid_nominal_checked": "full-grid oracle; includes test states",
            "training_grid_marginal": "training-state support only",
        },
    }
    (output / "provenance.json").write_text(
        json.dumps(provenance, indent=2, allow_nan=False) + "\n"
    )
    runs = []
    try:
        for seed in config["seeds"]:
            runs.append(run_seed(config, seed, manifest, arrays, external, output))
            print(
                json.dumps({"seed_complete": seed, "elapsed_seconds": time.monotonic() - clock}),
                flush=True,
            )
    except Exception as exc:
        failure = {
            "status": "failed",
            "completed_seeds": [x["seed"] for x in runs],
            "exception_type": type(exc).__name__,
            "message": str(exc),
            "elapsed_seconds": time.monotonic() - clock,
        }
        (output / "failure.json").write_text(json.dumps(failure, indent=2, allow_nan=False) + "\n")
        raise
    report = {
        "kind": "physical_grid_synthetic_noise_interventions",
        "smoke": smoke,
        "config": config,
        "source_commit": source,
        "config_sha256": digest(CONFIG),
        "started_utc": started,
        "elapsed_seconds": time.monotonic() - clock,
        "platform": platform.platform(),
        "versions": {p: version(p) for p in ("tierra-plus", "numpy")},
        "inputs": {
            "rcte_manifest": manifest,
            "photochemical_manifest": external[0] if external else None,
        },
        "control_roles": provenance["control_roles"],
        "runs": runs,
        "decisions": decisions(runs, config["required_seed_passes"], smoke),
    }
    (output / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--grid", type=Path, required=True)
    parser.add_argument("--external-grid", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--smoke", action="store_true")
    args = parser.parse_args()
    run(args.grid, args.output, args.external_grid, args.smoke)
